// Generates packages/grafana-ui/src/components/Icon/iconLoaders.gen.ts — a lazy
// loader per legacy IconName, pointing at a single @grafana/icons leaf module so
// each icon code-splits into its own chunk.
//
// Run: node scripts/generate-icon-loaders.mjs
//
// GRAFANA_ONLY_MAPPINGS covers names the upstream migrations table doesn't map.
// Every entry here is a gap to push back to grafana/design; the generator fails
// if a name stops needing an override so the list can't rot.
import fs from 'node:fs';
import path from 'node:path';

import { migrations } from '@grafana/icons/migrations';
import * as barrel from '@grafana/icons';

const OUT = 'packages/grafana-ui/src/components/Icon/iconLoaders.gen.ts';
const ICON_TYPES = 'packages/grafana-data/src/types/icon.ts';

const GRAFANA_ONLY_MAPPINGS = {
  // Upstream ships the glyph but never added the mapping row.
  'message-sparkles': 'MessageSparkles',
  // No dedicated enterprise mark upstream; the plain GitHub mark is the closest.
  'github-enterprise': 'Github',
  // Nav pin state. Lucide has no solid pin, so the pinned state reuses Pin and
  // the unpinned state uses PinOff. Revisit if upstream adds a PinSolid.
  'gf-pin-filled': 'Pin',
  'gf-pin-unfilled': 'PinOff',
  // Upstream declines to map these two (dead products). Alerting still renders
  // them for contact-point types, so they need a target.
  'google-hangouts-alt': 'Google',
  hipchat: 'MessageCircle',
};

// 'fa fa-spinner' is a deprecated alias Icon rewrites to 'spinner' before
// lookup, but it's a member of IconName so the Record needs the key.
const DEPRECATED_ALIASES = { 'fa fa-spinner': 'spinner' };

function readCoreIconNames() {
  const src = fs.readFileSync(ICON_TYPES, 'utf8');
  const body = src.split('availableIconsIndex = {')[1].split('\n};')[0];
  return [...body.matchAll(/^\s*'?([^\s':]+)'?:\s*true,/gm)].map((m) => m[1]);
}

const coreNames = readCoreIconNames();
const resolved = new Map();
const problems = [];
const unusedOverrides = new Set(Object.keys(GRAFANA_ONLY_MAPPINGS));

for (const name of coreNames) {
  const upstream = migrations[name];
  const override = GRAFANA_ONLY_MAPPINGS[name];

  if (upstream && override) {
    problems.push(`${name}: upstream now maps this to ${upstream}; drop the local override`);
    continue;
  }
  unusedOverrides.delete(name);

  const target = upstream ?? override;
  if (!target) {
    problems.push(`${name}: no mapping in @grafana/icons/migrations and no local override`);
    continue;
  }
  if (typeof barrel[target] !== 'function') {
    problems.push(`${name}: mapped to ${target}, which @grafana/icons does not export`);
    continue;
  }
  resolved.set(name, target);
}

for (const stale of unusedOverrides) {
  problems.push(`${stale}: local override is no longer a known icon name; remove it`);
}

if (problems.length) {
  console.error(`Cannot generate ${OUT}:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

const entry = (name, target) =>
  `  ${JSON.stringify(name)}: () => import('@grafana/icons/${target}').then((m) => m.${target}),`;

const lines = [...resolved].map(([name, target]) => entry(name, target));
for (const [alias, canonical] of Object.entries(DEPRECATED_ALIASES)) {
  lines.push(entry(alias, resolved.get(canonical)));
}

const nameLines = [...resolved].map(([name, target]) => `  ${JSON.stringify(name)}: ${JSON.stringify(target)},`);
for (const [alias, canonical] of Object.entries(DEPRECATED_ALIASES)) {
  nameLines.push(`  ${JSON.stringify(alias)}: ${JSON.stringify(resolved.get(canonical))},`);
}

const contents = `// Code generated by scripts/generate-icon-loaders.mjs. DO NOT EDIT.
// Regenerate after bumping @grafana/icons or changing availableIconsIndex.
import { type IconName } from '@grafana/data';
import { type SVGComponent } from '@grafana/icons';

export const iconLoaders: Record<IconName, () => Promise<SVGComponent>> = {
${lines.join('\n')}
};

/**
 * The same mapping as \`iconLoaders\`, but as plain component names. Lets a caller
 * that has already imported the whole \`@grafana/icons\` barrel — the test
 * environment — resolve every icon synchronously. Strings only, so importing this
 * pulls no icon code.
 */
export const iconComponentNames: Record<IconName, string> = {
${nameLines.join('\n')}
};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, contents);
console.log(`Wrote ${OUT} — ${resolved.size} icons + ${Object.keys(DEPRECATED_ALIASES).length} alias`);
