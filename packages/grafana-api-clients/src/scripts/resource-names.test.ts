import { type OpenAPIV3 } from 'openapi-types';

import { renderResourceNames, resourceNamesFromSpec } from './resource-names';

const listOperation = (kind: string) => ({
  'x-kubernetes-action': 'list',
  'x-kubernetes-group-version-kind': { group: 'provisioning.grafana.app', version: 'v0alpha1', kind },
});

const spec = (paths: Record<string, unknown>) =>
  // eslint-disable-next-line @typescript-eslint/consistent-type-assertions
  ({ openapi: '3.0.0', info: { title: 'test', version: 'v0alpha1' }, paths }) as OpenAPIV3.Document;

describe('resourceNamesFromSpec', () => {
  it('names each kind by the path its list operation is served at', () => {
    const names = resourceNamesFromSpec(
      spec({
        '/repositories': { get: listOperation('Repository') },
        '/jobs': { get: listOperation('Job') },
      })
    );

    expect(names).toEqual({ Job: 'jobs', Repository: 'repositories' });
  });

  it('ignores operations on single resources, subresources and custom routes', () => {
    const names = resourceNamesFromSpec(
      spec({
        '/repositories/{name}': {
          get: { 'x-kubernetes-action': 'get', 'x-kubernetes-group-version-kind': { kind: 'Repository' } },
        },
        '/repositories/{name}/files': {
          get: { 'x-kubernetes-action': 'connect', 'x-kubernetes-group-version-kind': { kind: 'ResourceWrapper' } },
        },
        '/search': { get: { operationId: 'search' } },
      })
    );

    expect(names).toEqual({});
  });
});

describe('renderResourceNames', () => {
  it('renders a const map keyed by kind', () => {
    expect(renderResourceNames({ Job: 'jobs', Repository: 'repositories' })).toMatchInlineSnapshot(`
      "// Generated by \`pnpm generate-apis\` from the OpenAPI spec. Do not edit.

      /** Resource name each kind of this API group version is served under, keyed by Kubernetes Kind. */
      export const API_RESOURCES = {
        Job: 'jobs',
        Repository: 'repositories',
      } as const;
      "
    `);
  });
});
