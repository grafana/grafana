import { type OpenAPIV3 } from 'openapi-types';

/** Kubernetes Kind -> the resource name the apiserver serves it under. */
export type ResourceNames = Record<string, string>;

/**
 * The resource name of every kind a processed spec serves, taken from its list operations: the
 * apiserver stamps each one with the kind it lists, and the path it is served at starts with the
 * resource name. Kubernetes plurals are declared per kind rather than computed, so this is the only
 * client-side authority for them (`Repository` is served as `repositories`, not `repositorys`).
 */
export function resourceNamesFromSpec(spec: OpenAPIV3.Document): ResourceNames {
  const names: ResourceNames = {};

  for (const [path, pathItem] of Object.entries(spec.paths ?? {})) {
    for (const operation of Object.values(pathItem ?? {})) {
      if (!isListOperation(operation)) {
        continue;
      }
      const resource = path.split('/').filter(Boolean)[0];
      if (resource) {
        names[operation['x-kubernetes-group-version-kind'].kind] = resource;
      }
    }
  }

  // Sorted so the generated file only changes when the API does. Kind names are ASCII identifiers.
  return Object.fromEntries(Object.entries(names).sort(([a], [b]) => (a < b ? -1 : 1)));
}

type ListOperation = OpenAPIV3.OperationObject & {
  'x-kubernetes-group-version-kind': { kind: string };
};

function isListOperation(operation: unknown): operation is ListOperation {
  if (typeof operation !== 'object' || operation === null) {
    return false;
  }
  if (!('x-kubernetes-action' in operation) || operation['x-kubernetes-action'] !== 'list') {
    return false;
  }
  const gvk = 'x-kubernetes-group-version-kind' in operation ? operation['x-kubernetes-group-version-kind'] : undefined;
  return typeof gvk === 'object' && gvk !== null && 'kind' in gvk && typeof gvk.kind === 'string';
}

/** Renders the `resources.gen.ts` emitted next to a client's `endpoints.gen.ts`. */
export function renderResourceNames(names: ResourceNames): string {
  const entries = Object.entries(names)
    .map(([kind, resource]) => `  ${kind}: '${resource}',`)
    .join('\n');

  return `// Generated by \`pnpm generate-apis\` from the OpenAPI spec. Do not edit.

/** Resource name each kind of this API group version is served under, keyed by Kubernetes Kind. */
export const API_RESOURCES = {
${entries}
} as const;
`;
}
