package legacy_storage

import (
	"context"
	"encoding/json"
	"fmt"

	"github.com/grafana/grafana/pkg/infra/log"
	"github.com/grafana/grafana/pkg/services/featuremgmt"
	"github.com/grafana/grafana/pkg/services/ngalert/models"
	v1 "github.com/grafana/grafana/pkg/services/ngalert/notifier/legacy_storage/v1"
	"github.com/grafana/grafana/pkg/services/ngalert/notifier/legacy_storage/v1/store"
	"github.com/grafana/grafana/pkg/services/ngalert/remote/client"
)

type crypto interface {
	EncryptExtraConfigs(ctx context.Context, config *v1.AMConfigV1) error
	DecryptExtraConfigs(ctx context.Context, config *v1.AMConfigV1) error
}

type amConfigStore interface {
	GetLatestAlertmanagerConfiguration(ctx context.Context, orgID int64) (*models.AlertConfiguration, error)
	UpdateAlertmanagerConfiguration(ctx context.Context, cmd *models.SaveAlertmanagerConfigurationCmd) error
}

func DeserializeAlertmanagerConfig(config []byte) (*store.AMConfigDB, error) {
	result := store.AMConfigDB{}
	if err := json.Unmarshal(config, &result); err != nil {
		return nil, makeErrBadAlertmanagerConfiguration(err)
	}
	return &result, nil
}

func SerializeAlertmanagerConfig(config v1.AMConfigV1) ([]byte, error) {
	dbModel, err := v1.ToDBModel(&config)
	if err != nil {
		return nil, err
	}
	return json.Marshal(dbModel)
}

// limitsProvider mirrors provisioning.LimitsProvider; it is redeclared here because provisioning imports this package.
type limitsProvider interface {
	GetLimits(ctx context.Context) (*client.TenantLimits, error)
}

// configSizeThresholdPercent leaves headroom below the remote limit because the payload sent to the
// remote Alertmanager is larger than the stored blob (autogenerated routes, SMTP and runtime settings).
const configSizeThresholdPercent = 90

type ConfigRevision struct {
	Config           *v1.AMConfigV1
	ConcurrencyToken string
	Version          string

	// storedSize is the size in bytes of the serialized configuration this revision was read from.
	storedSize int
}
type alertmanagerConfigStoreImpl struct {
	store    amConfigStore
	crypto   crypto
	features featuremgmt.FeatureToggles
	limits   limitsProvider
	logger   log.Logger
}

func NewAlertmanagerConfigStore(store amConfigStore, crypto crypto, features featuremgmt.FeatureToggles) *alertmanagerConfigStoreImpl {
	return &alertmanagerConfigStoreImpl{store: store, crypto: crypto, features: features, logger: log.New("ngalert.notifier.config-store")}
}

// WithLimitsProvider returns a copy of the store that rejects configurations exceeding the remote Alertmanager size limit.
func (a *alertmanagerConfigStoreImpl) WithLimitsProvider(p limitsProvider) *alertmanagerConfigStoreImpl {
	c := *a
	c.limits = p
	return &c
}

func (a alertmanagerConfigStoreImpl) Get(ctx context.Context, orgID int64) (*ConfigRevision, error) {
	alertManagerConfig, err := a.store.GetLatestAlertmanagerConfiguration(ctx, orgID)
	if err != nil {
		return nil, err
	}

	if alertManagerConfig == nil {
		return nil, ErrNoAlertmanagerConfiguration.Errorf("")
	}

	concurrencyToken := alertManagerConfig.ConfigurationHash
	dbCfg, err := DeserializeAlertmanagerConfig([]byte(alertManagerConfig.AlertmanagerConfiguration))
	if err != nil {
		return nil, err
	}
	cfg := v1.ToModel(dbCfg)

	err = a.crypto.DecryptExtraConfigs(ctx, cfg)
	if err != nil {
		return nil, fmt.Errorf("failed to decrypt extra configurations: %w", err)
	}

	return &ConfigRevision{
		Config:           cfg,
		ConcurrencyToken: concurrencyToken,
		Version:          alertManagerConfig.ConfigurationVersion,
		storedSize:       len(alertManagerConfig.AlertmanagerConfiguration),
	}, nil
}

func (a alertmanagerConfigStoreImpl) Save(ctx context.Context, revision *ConfigRevision, orgID int64) error {
	err := a.crypto.EncryptExtraConfigs(ctx, revision.Config)
	if err != nil {
		return fmt.Errorf("failed to encrypt extra configurations: %w", err)
	}

	serialized, err := SerializeAlertmanagerConfig(*revision.Config)
	if err != nil {
		return err
	}
	if err := a.validateConfigSize(ctx, len(serialized), revision.storedSize); err != nil {
		return err
	}
	return a.store.UpdateAlertmanagerConfiguration(ctx, &models.SaveAlertmanagerConfigurationCmd{
		AlertmanagerConfiguration: string(serialized),
		ConfigurationVersion:      revision.Version,
		FetchedConfigurationHash:  revision.ConcurrencyToken,
		Default:                   false,
		OrgID:                     orgID,
	})
}

// validateConfigSize fails open when limits are unavailable, so a remote Alertmanager outage does not block writes.
// Writes that do not grow the configuration return before the limits lookup, so shrinking writes never
// wait on the remote Alertmanager while a transaction is open.
func (a alertmanagerConfigStoreImpl) validateConfigSize(ctx context.Context, newSize, storedSize int) error {
	if a.limits == nil || newSize <= storedSize {
		return nil
	}
	limits, err := a.limits.GetLimits(ctx)
	if err != nil {
		if a.logger != nil {
			a.logger.Warn("Failed to fetch limits, skipping config size validation", "error", err)
		}
		return nil
	}
	if limits == nil || limits.Config == nil || limits.Config.MaxGrafanaConfigSizeBytes <= 0 {
		return nil
	}
	threshold := limits.Config.MaxGrafanaConfigSizeBytes * configSizeThresholdPercent / 100
	if newSize > threshold {
		return makeErrAlertmanagerConfigSizeExceeded(newSize, threshold)
	}
	return nil
}
