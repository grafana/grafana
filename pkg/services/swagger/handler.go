package swagger

import (
	"embed"
	"errors"
	"fmt"
	"html/template"
	"net/http"
	"syscall"

	"github.com/grafana/grafana/pkg/api/dtos"
	"github.com/grafana/grafana/pkg/api/webassets"
	"github.com/grafana/grafana/pkg/infra/log"
	"github.com/grafana/grafana/pkg/middleware"
	"github.com/grafana/grafana/pkg/services/contexthandler"
	"github.com/grafana/grafana/pkg/services/licensing"
	"github.com/grafana/grafana/pkg/setting"
	"github.com/grafana/grafana/pkg/util/errhttp"
)

// buildDir is the bundler output directory holding the swagger app. It must
// match the output path configured in scripts/rspack/rspack.swagger.ts.
const buildDir = "build-swagger"

// Templates setup.
var (
	//go:embed swagger.html
	templatesFS embed.FS

	htmlTemplates = template.Must(template.New("html").Delims("[[", "]]").ParseFS(templatesFS, `swagger.html`))
)

// indexTemplate panics at init rather than per request if the embedded template
// ever stops matching the name parsed above.
var indexTemplate = func() *template.Template {
	t := htmlTemplates.Lookup("swagger.html")
	if t == nil {
		panic("missing swagger template")
	}
	return t
}()

type IndexViewData struct {
	IsDevelopmentEnv bool

	Assets *dtos.EntryPointAssets

	// Nonce is a cryptographic identifier for use with Content Security Policy.
	Nonce string

	CSPEnabled bool
	CSPContent string
}

// Handler renders the swagger based API navigator. It is shared by the core
// HTTPServer and the standalone swagger service so both serve the same page.
type Handler struct {
	log     log.Logger
	index   *template.Template
	cfg     *setting.Cfg
	license licensing.Licensing
}

func NewHandler(cfg *setting.Cfg, license licensing.Licensing) *Handler {
	return &Handler{
		log:     log.New("swagger"),
		index:   indexTemplate,
		cfg:     cfg,
		license: license,
	}
}

// HandleRedirect points the deprecated /swagger-ui and /openapi3 paths at /swagger.
func HandleRedirect(w http.ResponseWriter, r *http.Request) {
	http.Redirect(w, r, "swagger", http.StatusMovedPermanently)
}

func (h *Handler) HandleRequest(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()

	assets, err := webassets.GetWebAssets(ctx, buildDir, h.cfg, h.license)
	if err != nil {
		errhttp.Write(ctx, err, w)
		return
	}

	// The nonce is generated by the CSP middleware. It is absent when CSP is
	// disabled, in which case the template renders empty nonce attributes.
	var nonce string
	if reqCtx := contexthandler.FromContext(ctx); reqCtx != nil {
		nonce = reqCtx.RequestNonce
	}

	data := IndexViewData{
		IsDevelopmentEnv: h.cfg.Env == setting.Dev,
		Assets:           assets,
		Nonce:            nonce,
	}

	if h.cfg.CSPEnabled {
		data.CSPEnabled = true
		hosts := middleware.CSPHostLists{FormActionAdditionalHosts: h.cfg.FormActionAdditionalHosts}
		data.CSPContent = middleware.ReplacePolicyVariables(h.cfg.CSPTemplate, h.cfg.AppURL, hosts, nonce)
	}

	w.Header().Set("Content-Type", "text/html; charset=UTF-8")
	w.WriteHeader(http.StatusOK)
	if err := h.index.Execute(w, &data); err != nil {
		if errors.Is(err, syscall.EPIPE) { // Client has stopped listening.
			return
		}
		panic(fmt.Sprintf("Error rendering swagger\n %s", err.Error()))
	}
}
