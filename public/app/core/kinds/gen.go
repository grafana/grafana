//go:build ignore
// +build ignore

//go:generate go run gen.go

// Writes coreKinds.gen.ts from the app manifests compiled into this binary, so
// the kind registry does not restate a kind's API group, Kind and resource.
// Presentation (icon, labels, routes) stays hand-written in coreKinds.ts.
package main

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"sort"
	"strings"

	"github.com/grafana/grafana/pkg/storage/unified/resource"
)

const output = "coreKinds.gen.ts"

var identifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// id is what discovery reports for a kind and what the registry must agree on.
type id struct {
	group    string
	kind     string
	resource string
}

func main() {
	// Kind names are unique only within an app, not across Grafana: both the
	// alerting notifications and the alerting rules app declare a Config kind.
	kinds := map[string]map[string]id{}
	for _, manifest := range resource.AppManifests() {
		if manifest.AppName == "" {
			log.Fatalf("manifest for group %q has no app name", manifest.Group)
		}
		for _, version := range manifest.Versions {
			for _, k := range version.Kinds {
				resourceName := k.Resource
				if resourceName == "" {
					// The app SDK defaults an omitted Resource to the lowercased
					// plural only when it reads JSON; a generated manifest may
					// leave it empty.
					resourceName = strings.ToLower(k.Plural)
				}
				next := id{group: manifest.Group, kind: k.Kind, resource: resourceName}
				if kinds[manifest.AppName] == nil {
					kinds[manifest.AppName] = map[string]id{}
				}
				// A kind is usually served in several versions; its identity has
				// to be the same in all of them.
				if prev, ok := kinds[manifest.AppName][k.Kind]; ok {
					if prev != next {
						log.Fatalf("kind %q of app %q differs between versions: %+v vs %+v",
							k.Kind, manifest.AppName, prev, next)
					}
					continue
				}
				kinds[manifest.AppName][k.Kind] = next
			}
		}
	}

	apps := make([]string, 0, len(kinds))
	for app := range kinds {
		apps = append(apps, app)
	}
	sort.Strings(apps)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gen.go from the app manifests compiled into Grafana. DO NOT EDIT.\n\n")
	buf.WriteString("export const GENERATED_KINDS = {\n")
	for _, app := range apps {
		fmt.Fprintf(&buf, "  %s: {\n", key(app))
		names := make([]string, 0, len(kinds[app]))
		for kind := range kinds[app] {
			names = append(names, kind)
		}
		sort.Strings(names)
		for _, kind := range names {
			k := kinds[app][kind]
			fmt.Fprintf(&buf, "    %s: { group: '%s', kind: '%s', resource: '%s' },\n",
				key(kind), k.group, k.kind, k.resource)
		}
		buf.WriteString("  },\n")
	}
	buf.WriteString("} as const;\n")

	_, self, _, ok := runtime.Caller(0)
	if !ok {
		log.Fatal("cannot locate gen.go")
	}
	path := filepath.Join(filepath.Dir(self), output)
	if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %s: %d apps\n", path, len(apps))
}

// key quotes an object member name when it is not a valid TypeScript identifier.
func key(name string) string {
	if identifier.MatchString(name) {
		return name
	}
	return "'" + strings.ReplaceAll(name, "'", "\\'") + "'"
}
