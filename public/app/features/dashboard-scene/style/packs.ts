export const STYLE_PACKS: StylePack[] = [grafanaPack, newsroomPack, fieldGuidePack, pinstripePack, keynotePack];

export function getStylePack(id: string | undefined): StylePack | undefined {
  return STYLE_PACKS.find((pack) => pack.id === id);
}

export function findOption<T extends StylePalette | StyleAccent | StyleTypography>(
  options: T[],
  id: string | undefined
): T | undefined {
  return id ? options.find((option) => option.id === id) : undefined;
}
