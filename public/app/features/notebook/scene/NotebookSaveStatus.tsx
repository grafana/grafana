import { css } from '@emotion/css';
import { useEffect, useState } from 'react';

import { type GrafanaTheme2 } from '@grafana/data';
import { t } from '@grafana/i18n';
import { Button, Stack, Text, Tooltip, useStyles2 } from '@grafana/ui';

import { type NotebookAutosave, type NotebookSaveStatus as SaveStatus } from './NotebookAutosave';

/** The same two seconds `AutoSaveField` waits, so a saved notebook reads like the rest of Grafana. */
const SAVED_VISIBLE_MS = 2000;

/**
 * Most saves land sooner than this. A word that appears and disappears in under a sixth of a second is a
 * flicker rather than something anyone can read, so only a save slow enough to notice says it is saving.
 */
const SAVING_SHOWN_AFTER_MS = 150;

/**
 * What the notebook's autosave is doing, in words. There is no save button, so nothing else tells a user
 * whether their work is safe, including when the assistant is the one writing.
 *
 * Nothing is shown while `idle`. Saying "Saved" about a notebook nobody has touched claims something we
 * did not do, and a label that is always there stops being information.
 *
 * `reserveSpace` keeps room for the longest label while idle. Edit mode uses it, so the undo and redo
 * buttons stay put when the assistant writes. View mode skips it. There it costs a line on a narrow
 * screen, to avoid a move that lasts one quick save.
 */
export function NotebookSaveStatus({
  autosave,
  reserveSpace = false,
}: {
  autosave: NotebookAutosave;
  reserveSpace?: boolean;
}) {
  const { status, errorMessage, isConflict } = autosave.useState();
  const styles = useStyles2(getStyles);
  const [savedExpired, setSavedExpired] = useState(false);
  const [savingShown, setSavingShown] = useState(false);

  useEffect(() => {
    setSavedExpired(false);

    if (status !== 'saved') {
      return;
    }

    const timeout = setTimeout(() => setSavedExpired(true), SAVED_VISIBLE_MS);
    return () => clearTimeout(timeout);
  }, [status]);

  useEffect(() => {
    setSavingShown(false);

    if (status !== 'saving') {
      return;
    }

    const timeout = setTimeout(() => setSavingShown(true), SAVING_SHOWN_AFTER_MS);
    return () => clearTimeout(timeout);
  }, [status]);

  // A save always starts from unsaved changes, so a save too quick to announce keeps saying that instead.
  const shown = status === 'saving' && !savingShown ? 'pending' : status;

  const labels: Record<Exclude<SaveStatus, 'idle'>, string> = {
    pending: t('notebooks.save-status.pending', 'Unsaved changes'),
    saving: t('notebooks.save-status.saving', 'Saving…'),
    saved: t('notebooks.save-status.saved', 'Saved'),
    error: t('notebooks.save-status.failed', 'Save failed'),
  };

  // The row wraps when it runs out of room, so a label that comes and goes would move the undo and redo
  // buttons. The slot is as wide as the longest label. Length counts characters, not pixels, so that
  // width is close, not exact.
  const widest = [labels.pending, labels.saving, labels.saved].reduce((longest, label) =>
    label.length > longest.length ? label : longest
  );

  if (shown === 'idle' || (shown === 'saved' && savedExpired)) {
    return reserveSpace ? <div className={styles.slot} data-widest-label={widest} /> : null;
  }

  const label = (
    <Text variant="bodySmall" color="secondary">
      {labels[shown]}
    </Text>
  );

  const content = (
    <Stack gap={0.5} alignItems="center">
      {/* The message is the only thing saying WHY it failed, and too long to sit in the row. */}
      {shown === 'error' && errorMessage ? (
        <Tooltip content={errorMessage}>
          <span>{label}</span>
        </Tooltip>
      ) : (
        label
      )}
      {/* Retrying a conflict would just resend the same revision and fail the same way again; the
          confirm modal autosave already raised is where that case gets resolved, not this button. */}
      {shown === 'error' && !isConflict ? (
        <Button variant="secondary" fill="text" size="sm" onClick={() => autosave.retryFromButton()}>
          {t('notebooks.save-status.retry', 'Retry')}
        </Button>
      ) : null}
    </Stack>
  );

  // A failure stays on screen and can carry a button, so it takes the room it needs.
  if (shown === 'error' || !reserveSpace) {
    return content;
  }

  return (
    <div className={styles.slot} data-widest-label={widest}>
      {content}
    </div>
  );
}

const getStyles = (theme: GrafanaTheme2) => ({
  // The label and an invisible copy of the widest label share one grid cell, so the cell is as wide
  // as the widest. The copy is generated by CSS, so there is no second text for screen readers.
  slot: css({
    display: 'grid',
    justifyItems: 'end',
    alignItems: 'center',
    '&::after': {
      ...theme.typography.sm,
      content: 'attr(data-widest-label)',
      gridArea: '1 / 1',
      visibility: 'hidden',
      whiteSpace: 'nowrap',
      height: 0,
      overflow: 'hidden',
    },
    '& > *': {
      gridArea: '1 / 1',
    },
  }),
});
